/**
 * Precomputes two things `next build` needs read from disk, into modules the
 * Cloudflare Workers runtime can import instead — Workers has no filesystem,
 * so anything read via `node:fs` at request time (rather than at build time)
 * throws `[unenv] fs.* is not implemented yet!` there.
 *
 *   node scripts/build-static-assets.mjs   (runs automatically on `prebuild`)
 *
 * Writes lib/generated/static-assets.ts:
 *
 *   ogDisplayFontBase64   app/og-display.ttf, base64-encoded. Read by
 *                         app/opengraph-image.tsx, which renders on request
 *                         (`dynamic = 'force-static'` only caches the result
 *                         after the first render — it still has to run once).
 *   publicFiles           Every path under public/, as the site addresses it
 *                         (leading slash, POSIX separators). lib/media.ts
 *                         checks membership instead of calling `existsSync`.
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const fontBase64 = readFileSync(resolve(ROOT, 'app/og-display.ttf')).toString('base64');

function walk(dir, base = '') {
  const paths = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const webPath = `${base}/${entry.name}`;
    if (entry.isDirectory()) {
      paths.push(...walk(join(dir, entry.name), webPath));
    } else {
      paths.push(webPath);
    }
  }
  return paths;
}

const publicFiles = walk(resolve(ROOT, 'public')).sort();

mkdirSync(resolve(ROOT, 'lib/generated'), { recursive: true });
writeFileSync(
  resolve(ROOT, 'lib/generated/static-assets.ts'),
  `// GENERATED by scripts/build-static-assets.mjs — do not edit.\n` +
    `export const ogDisplayFontBase64 = ${JSON.stringify(fontBase64)};\n` +
    `export const publicFiles: ReadonlySet<string> = new Set(${JSON.stringify(publicFiles)});\n`,
);

console.log(`static-assets: font ${(fontBase64.length / 1024).toFixed(1)}KB base64, ${publicFiles.length} public files indexed`);
