/**
 * Generates data/training.json.
 *
 * This exists ONLY because the real Workout Buddy export was not ready when
 * the site was built. It writes the exact schema the real export uses, so
 * replacing the file is a straight swap — delete this script at that point.
 *
 *   node scripts/generate-placeholder-training.mjs
 *
 * Deterministic (seeded PRNG), so the committed JSON, the field buffer and the
 * poster never change unless the inputs do.
 */

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** mulberry32 — small, fast, seedable. */
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = rng(20240603);

/** Two compound lifts per training day, eight in rotation. */
const LIFTS = [
  { id: 'back-squat', name: 'Back Squat', day: 'lower-a', start: 225, end: 340, plateau: 0 },
  { id: 'romanian-deadlift', name: 'Romanian Deadlift', day: 'lower-a', start: 185, end: 300, plateau: 0.05 },
  { id: 'bench-press', name: 'Bench Press', day: 'upper-a', start: 165, end: 240, plateau: 0.12 },
  { id: 'barbell-row', name: 'Barbell Row', day: 'upper-a', start: 135, end: 200, plateau: 0 },
  { id: 'deadlift', name: 'Deadlift', day: 'lower-b', start: 275, end: 430, plateau: 0 },
  { id: 'front-squat', name: 'Front Squat', day: 'lower-b', start: 155, end: 240, plateau: 0.08 },
  { id: 'overhead-press', name: 'Overhead Press', day: 'upper-b', start: 105, end: 145, plateau: 0.34 },
  { id: 'incline-bench-press', name: 'Incline Bench Press', day: 'upper-b', start: 135, end: 195, plateau: 0.21 },
];

/** Training days: Mon, Tue, Thu, Fri. */
const DAY_PLAN = [
  { weekday: 1, block: 'lower-a' },
  { weekday: 2, block: 'upper-a' },
  { weekday: 4, block: 'lower-b' },
  { weekday: 5, block: 'upper-b' },
];

/** Rep schemes rotate on a four-week wave. */
const SCHEMES = [
  { sets: 5, reps: 5, intensity: 0.84 },
  { sets: 4, reps: 6, intensity: 0.8 },
  { sets: 3, reps: 8, intensity: 0.74 },
  { sets: 5, reps: 3, intensity: 0.92 },
];

const START = new Date(Date.UTC(2024, 5, 3)); // Monday 3 June 2024
const WEEKS = 108;

/** Weeks off. Week 41 was a chest infection; week 78 was a house move. */
const GAPS = new Set([41, 42, 43, 78]);

const round5 = (n) => Math.round(n / 5) * 5;
const iso = (d) => d.toISOString().slice(0, 10);

const sessions = [];

for (let week = 0; week < WEEKS; week += 1) {
  if (GAPS.has(week)) continue;

  const progress = week / (WEEKS - 1);
  const scheme = SCHEMES[week % SCHEMES.length];
  // Deload every sixth week: same movements, ~12% off the bar.
  const deload = week > 0 && week % 6 === 5;

  for (const plan of DAY_PLAN) {
    const date = new Date(START);
    date.setUTCDate(date.getUTCDate() + week * 7 + (plan.weekday - 1));

    const lifts = LIFTS.filter((l) => l.day === plan.block);
    if (lifts.length === 0) continue;

    const entries = [];
    for (const lift of lifts) {
      // Strength curve: fast early, flattening later, with a plateau window
      // where the lift stops moving for a couple of months.
      const curve = 1 - Math.pow(1 - progress, 1.7);
      const stalled =
        lift.plateau > 0 && progress > lift.plateau && progress < lift.plateau + 0.18
          ? (progress - lift.plateau) / 0.18
          : null;
      const shaped = stalled === null ? curve : 1 - Math.pow(1 - lift.plateau, 1.7);

      let oneRm = lift.start + (lift.end - lift.start) * shaped;
      oneRm *= 1 + (rand() - 0.5) * 0.03; // day-to-day noise
      let working = oneRm * scheme.intensity;
      if (deload) working *= 0.88;

      const weight = round5(Math.max(45, working));
      // The last set of a heavy day sometimes drops a rep or two.
      const sets = [];
      for (let s = 0; s < scheme.sets; s += 1) {
        const short = s === scheme.sets - 1 && !deload && rand() < 0.22 ? (rand() < 0.5 ? 1 : 2) : 0;
        sets.push({ weight, reps: Math.max(1, scheme.reps - short) });
      }

      entries.push({
        lift: lift.id,
        sets: sets.length,
        reps: scheme.reps,
        weight,
        logged: sets,
      });
    }

    sessions.push({ date: iso(date), block: plan.block, entries });
  }
}

const setCount = sessions.reduce((n, s) => n + s.entries.reduce((m, e) => m + e.logged.length, 0), 0);
const repCount = sessions.reduce(
  (n, s) => n + s.entries.reduce((m, e) => m + e.logged.reduce((k, l) => k + l.reps, 0), 0),
  0,
);

const out = {
  $comment:
    'TODO: replace with the real Workout Buddy export. Generated by scripts/generate-placeholder-training.mjs — same schema, plausible numbers. Nothing in the site reads Math.random(); the field is wired to this file.',
  athlete: 'Cody Cantrell',
  unit: 'lb',
  exported: '2026-07-01',
  placeholder: true,
  lifts: LIFTS.map(({ id, name }) => ({ id, name })),
  sessions,
};

mkdirSync(resolve(ROOT, 'data'), { recursive: true });
writeFileSync(resolve(ROOT, 'data/training.json'), `${JSON.stringify(out, null, 1)}\n`);

console.log(
  `data/training.json — ${sessions.length} sessions, ${setCount} sets, ${repCount} reps, ${sessions[0].date} to ${sessions[sessions.length - 1].date}`,
);
